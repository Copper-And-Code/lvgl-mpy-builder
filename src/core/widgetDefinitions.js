export function createWidget(type, id, props = {}) {
  const definition = widgetDefinitions[type];
  if (!definition) {
    throw new Error(`Unknown widget type: ${type}`);
  }

  return {
    id,
    type,
    name: `${definition.name}_${id.slice(-4)}`,
    props: { ...definition.defaultProps, ...props },
    events: [],
    children: [],
  };
}
